#!/usr/bin/env node
// Rename originals in media-source/ to descriptive names from a classification pass, keep an undo map,
// and generate the typed mock-media manifest the placeholder content draws from.
//
// Usage: node scripts/media/apply-classification.mjs <work-dir> <src-dir> [--dry-run]
//   <work-dir> holds inventory.tsv (inventory.sh) and classification.json (visual tagging pass).
// Writes:  <src-dir>/_rename-map.tsv            old name → new name (undo with --undo)
//          app/content/data/media/mock.ts       manifest keyed by the new names
// Undo:    node scripts/media/apply-classification.mjs <work-dir> <src-dir> --undo
import { existsSync, readFileSync, renameSync, writeFileSync, mkdirSync } from "node:fs";
import { extname, join } from "node:path";

const [workDir, srcDir, flag] = process.argv.slice(2);
if (!workDir || !srcDir) {
  console.error("usage: apply-classification.mjs <work-dir> <src-dir> [--dry-run|--undo]");
  process.exit(1);
}
const mapPath = join(srcDir, "_rename-map.tsv");

if (flag === "--undo") {
  const rows = readFileSync(mapPath, "utf8").trim().split("\n").slice(1);
  for (const row of rows) {
    const [oldName, newName] = row.split("\t");
    if (existsSync(join(srcDir, newName))) renameSync(join(srcDir, newName), join(srcDir, oldName));
  }
  console.log(`restored ${rows.length} names`);
  process.exit(0);
}

const inventory = readFileSync(join(workDir, "inventory.tsv"), "utf8")
  .trim()
  .split("\n")
  .slice(1)
  .map((line) => {
    const [id, file, width, height, orientation] = line.split("\t");
    return { id, file, width: Number(width), height: Number(height), orientation };
  });
const tags = new Map(JSON.parse(readFileSync(join(workDir, "classification.json"), "utf8")).map((t) => [t.id, t]));

const slug = (s) =>
  String(s ?? "unknown")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40) || "unknown";

const entries = inventory.map((item) => {
  const tag = tags.get(item.id) ?? {};
  const n = item.id.replace("img-", "");
  const base = `${slug(tag.category)}_${slug(tag.subject)}_${item.orientation}_${n}`;
  return {
    ...item,
    name: `${base}${extname(item.file).toLowerCase().replace(".jpeg", ".jpg")}`,
    web: `${base}.jpg`,
    category: tag.category ?? "other",
    subject: tag.subject ?? "unknown",
    subjectGuess: Boolean(tag.subjectGuess),
    scene: tag.scene ?? null,
    watermark: tag.watermark ?? null,
    quality: tag.quality ?? null,
    uses: tag.uses ?? [],
    note: tag.note ?? "",
  };
});

if (flag !== "--dry-run") {
  for (const e of entries) {
    const from = join(srcDir, e.file);
    if (e.file !== e.name && existsSync(from)) renameSync(from, join(srcDir, e.name));
  }
  writeFileSync(mapPath, "old\tnew\n" + entries.map((e) => `${e.file}\t${e.name}`).join("\n") + "\n");
}

const manifest = entries.map((e) => ({
  id: e.id,
  src: `/media/mock/${e.web}`,
  original: e.name,
  width: e.width,
  height: e.height,
  orientation: e.orientation,
  category: e.category,
  subject: e.subject,
  subjectGuess: e.subjectGuess,
  scene: e.scene,
  watermark: e.watermark,
  quality: e.quality,
  uses: e.uses,
  note: e.note,
}));

mkdirSync("app/content/data/media", { recursive: true });
writeFileSync(
  "app/content/data/media/mock.ts",
  `// GENERATED by scripts/media/apply-classification.mjs — mock-up photos, tagged by a cheap visual pass.
// Subjects marked subjectGuess are unverified. Replace with real, captioned media in the content pass.
export type MockPhoto = (typeof mockPhotos)[number];

export const mockPhotos = ${JSON.stringify(manifest, null, 2)} as const;
`,
);

const byCategory = Object.groupBy(entries, (e) => e.category);
console.log(
  `${flag === "--dry-run" ? "[dry run] " : ""}${entries.length} photos:`,
  Object.entries(byCategory)
    .map(([c, list]) => `${c} ${list.length}`)
    .join(", "),
);
for (const e of entries.slice(0, 5)) console.log(`  ${e.file}  →  ${e.name}`);
